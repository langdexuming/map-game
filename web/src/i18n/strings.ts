/**
 * 替换文案中的 {key} 占位符
 * @param template 模板字符串
 * @param vars 占位符键值
 * @return 替换后的字符串
 */
export function formatStr(template: string, vars: Record<string, string | number>): string {
  let result = template;
  for (const [key, value] of Object.entries(vars)) {
    result = result.split(`{${key}}`).join(String(value));
  }
  return result;
}
